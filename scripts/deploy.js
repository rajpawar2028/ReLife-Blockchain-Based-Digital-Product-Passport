const hre = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  console.log("=================================================");
  console.log("  ReLife Smart Contract Deployment");
  console.log("=================================================");

  const [deployer] = await hre.ethers.getSigners();
  const network = await hre.ethers.provider.getNetwork();

  console.log(`Deploying network:   ${hre.network.name} (chainId: ${network.chainId})`);
  console.log(`Deployer account:    ${deployer.address}`);

  const balance = await hre.ethers.provider.getBalance(deployer.address);
  console.log(`Deployer balance:    ${hre.ethers.formatEther(balance)} ETH`);

  if (hre.network.name === "sepolia" && balance === 0n) {
    console.error("\n=======================================================");
    console.error("  [ReLife Deployment Error] Insufficient Testnet ETH");
    console.error("=======================================================");
    console.error(`Deployer wallet ${deployer.address} has 0 Sepolia ETH.`);
    console.error("Deploying smart contracts requires a small amount of test ETH to cover gas.");
    console.error("Please fund your wallet using one of these free faucets:");
    console.error("  1. Google Cloud Web3: https://cloud.google.com/application/web3/faucet/ethereum/sepolia");
    console.error("  2. Sepolia Faucet:    https://sepoliafaucet.com");
    console.error("  3. PoW Faucet:        https://sepolia-faucet.pk910.de");
    console.error("=======================================================\n");
    throw new Error("Deployer account has 0 Sepolia ETH.");
  }

  // Deploy ReLife contract
  console.log("\nDeploying ReLife contract...");
  const ReLifeFactory = await hre.ethers.getContractFactory("ReLife");
  const relife = await ReLifeFactory.deploy();
  await relife.waitForDeployment();

  const contractAddress = await relife.getAddress();
  console.log(`>>> ReLife deployed successfully at: ${contractAddress}`);

  // Confirm deployed bytecode is present on-chain
  const deployedCode = await hre.ethers.provider.getCode(contractAddress);
  if (!deployedCode || deployedCode === "0x" || deployedCode === "0x0") {
    throw new Error(`Deployment verification failed: getCode(${contractAddress}) returned "0x" (no bytecode found).`);
  }
  console.log(`>>> Bytecode confirmed on-chain (${(deployedCode.length - 2) / 2} bytes deployed).`);

  // Fetch full contract artifact for ABI
  const artifact = await hre.artifacts.readArtifact("ReLife");

  const contractData = {
    network: hre.network.name,
    chainId: Number(network.chainId),
    address: contractAddress,
    deployer: deployer.address,
    deployedAt: new Date().toISOString(),
    abi: artifact.abi,
  };

  // Ensure target directories exist
  const frontendDir = path.join(__dirname, "..", "frontend");
  const backendDir = path.join(__dirname, "..", "backend");

  if (!fs.existsSync(frontendDir)) {
    fs.mkdirSync(frontendDir, { recursive: true });
  }
  if (!fs.existsSync(backendDir)) {
    fs.mkdirSync(backendDir, { recursive: true });
  }

  const isSepolia = (hre.network.name === "sepolia" || network.chainId === 11155111n);

  if (isSepolia) {
    // 1. Write frontend/contract-data.json
    const frontendJsonPath = path.join(frontendDir, "contract-data.json");
    fs.writeFileSync(frontendJsonPath, JSON.stringify(contractData, null, 2));
    console.log(`Saved contract JSON to: ${frontendJsonPath}`);

    // 2. Write frontend/contract-data.js (for direct browser script inclusion without bundlers)
    const frontendJsPath = path.join(frontendDir, "contract-data.js");
    const jsContent = `// Auto-generated by scripts/deploy.js on ${new Date().toISOString()}
window.RELIFE_CONFIG = ${JSON.stringify(contractData, null, 2)};
`;
    fs.writeFileSync(frontendJsPath, jsContent);
    console.log(`Saved browser script to: ${frontendJsPath}`);

    // 3. Write backend/contract-data.json
    const backendJsonPath = path.join(backendDir, "contract-data.json");
    fs.writeFileSync(backendJsonPath, JSON.stringify(contractData, null, 2));
    console.log(`Saved backend JSON to:  ${backendJsonPath}`);
  } else {
    // Local / Hardhat runs write to a separate file that the frontend never reads
    const localhostJsonPath = path.join(__dirname, "..", "deployment.localhost.json");
    fs.writeFileSync(localhostJsonPath, JSON.stringify(contractData, null, 2));
    console.log(`[Local Run] Saved local deployment to: ${localhostJsonPath}`);
    console.log(`[Local Run] Preserved Sepolia frontend configuration.`);
  }

  // Etherscan verification (only for public live networks)
  if (hre.network.name === "sepolia" && process.env.ETHERSCAN_API_KEY) {
    console.log("\nWaiting for 6 block confirmations before verifying on Etherscan...");
    await relife.deploymentTransaction().wait(6);

    console.log("Verifying contract on Etherscan...");
    try {
      await hre.run("verify:verify", {
        address: contractAddress,
        constructorArguments: [],
      });
      console.log("Contract successfully verified on Etherscan!");
    } catch (error) {
      console.warn("Etherscan verification note:", error.message);
    }
  }

  console.log("\n=================================================");
  console.log("  Deployment completed successfully!");
  console.log("=================================================");
  return contractAddress;
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error("Deployment failed:", error);
    process.exit(1);
  });

